import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { compareVersions } from "../src/server/update-manager.mjs";
const metadata = JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8"));
const desktop = JSON.parse(await readFile(new URL("../packaging/windows/desktop-app/package.json", import.meta.url), "utf8"));
assert.equal(metadata.displayVersion, "k1.0.1");
assert.equal(desktop.version, metadata.version);
assert.ok(compareVersions(metadata.version, "9.3.2") > 0, "新迭代显示名不能导致旧安装版误判降级");
const shell = await readFile(new URL("../packaging/windows/desktop-app/main.mjs", import.meta.url), "utf8");
assert.match(shell, /APP_USER_MODEL_ID = "com\.shensi\.creativeengine"/u);
assert.match(shell, /--shensi-app-version=\$\{app\.getVersion\(\)\}/u, "数据版本和更新比较仍用数字版号");
assert.match(shell, /--shensi-display-version=\$\{displayVersion\}/u);
console.log("k1.0.1 display, monotonic update version and stable application identity passed");
