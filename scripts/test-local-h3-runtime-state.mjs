import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createLocalH3StatusStore } from "../src/local-h3-runtime-state.js";
import { visibleGenerationPickerProfiles } from "../src/generation-profiles.js";

const calls = [];
const store = createLocalH3StatusStore({ request: (action, profile) => new Promise((resolve, reject) => calls.push({ action, profile, resolve, reject })) });
const profile = { id: "video-local-h3", provider: "本地 H3", baseUrl: "http://127.0.0.1:8188", model: "minimax-h3-reference-video" };
const old = store.probe(profile);
const stopping = store.control("stop", profile);
calls[1].resolve({ installed: true, started: false, ready: false });
await stopping;
calls[0].resolve({ installed: true, started: true, ready: true });
await old;
assert.equal(store.peek(profile).result.ready, false, "迟到的启动前探测不能覆盖停止结果");
assert.equal(store.peek({ baseUrl: "http://127.0.0.1:9199" }).result, null, "不同地址状态不能串线");
const start = store.control("start", profile);
await assert.rejects(store.control("start", profile), /正在处理/u);
calls[2].reject(new Error("启动请求超时"));
await new Promise((resolve) => setImmediate(resolve));
calls[3].resolve({ installed: true, started: true, ready: false });
await assert.rejects(start, /超时/u);
assert.equal(store.peek(profile).result.started, true, "超时后仍需能够停止已拉起的进程");
assert.equal(store.peek(profile).error, "启动请求超时", "界面刷新不能吞掉启停错误");
assert.equal(visibleGenerationPickerProfiles({ videoConnections: [profile] }, "video").some((p) => p.id === profile.id), true);
const app = await readFile(new URL("../src/app.js", import.meta.url), "utf8");
assert.match(app, /channel === "video" && profile.provider === "本地 H3"\) return Boolean\(profile.baseUrl && profile.model\)/u, "本地 H3 不需要 API Key，也不能在恢复选择器中被过滤掉");
assert.match(app, /button.disabled = busy \|\| form.dataset.runtimeUnavailable === "true"/u);
assert.doesNotMatch(app, /cachedRuntime\?\.ready === true \|\| mediaCapabilityProbeFor/u);
assert.doesNotMatch(app, /whiteboardLocalH3Install|installLocalH3|一键装配本地 H3/u, "本地 H3 默认不再提供一键装配入口");
assert.match(app, /本地 H3 尚未配置完整，请先在本机准备运行环境/u);
console.log("local H3 UI: stale probes, isolated endpoints, pending start/stop, no-key picker and disabled generation passed");
