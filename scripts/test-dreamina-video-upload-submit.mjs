import assert from "node:assert/strict";
import { runKnownUnsubmittedVideoUpload } from "../src/cli/dreamina-video-upload-submit.mjs";
const text = 'upload resource "reference.png": ApplyImageUpload: context deadline exceeded';
const base = { taskId: value => value.providerTaskId || JSON.parse(value.stdout || "{}").submit_id || "", knownUploadFailure: value => value.includes("ApplyImageUpload"), retries: 4, delay: async () => {} };
let calls = 0;
await assert.rejects(runKnownUnsubmittedVideoUpload({ ...base, run: async () => { calls++; return { stdout: JSON.stringify({ error: text }) }; } }), error => error.code === "DREAMINA_REFERENCE_UPLOAD_NO_TASK" && error.submissionOutcomeKnown === true && JSON.parse(error.stdout).error === text);
assert.equal(calls, 5, "结构化的无任务上传错误采用既有有限重试");
calls = 0;
const receipt = await runKnownUnsubmittedVideoUpload({ ...base, run: async () => { calls++; return { stdout: JSON.stringify({ submit_id: "original", error: text }) }; } });
assert.equal(calls, 1); assert.ok(receipt.stdout.includes("original"), "已返回任务号绝不重提");
calls = 0;
await assert.rejects(runKnownUnsubmittedVideoUpload({ ...base, run: async () => { calls++; throw Object.assign(new Error(text), { providerTaskId: "original" }); } }), error => error.providerTaskId === "original");
assert.equal(calls, 1);
calls = 0;
await assert.rejects(runKnownUnsubmittedVideoUpload({ ...base, run: async () => { calls++; throw new Error("unexpected disconnect"); } }), /unexpected disconnect/u);
assert.equal(calls, 1, "未知提交结果不能当作无任务上传失败");
calls = 0;
await runKnownUnsubmittedVideoUpload({ ...base, run: async () => { calls++; if (calls === 1) throw new Error(text); return { stdout: '{"submit_id":"created"}' }; } });
assert.equal(calls, 2);
console.log("Dreamina video upload retry/no-duplicate receipt policy passed");
