const translateTrimmed = (value) => {
  const normalized = String(value ?? "").trim();
  if (!normalized) return normalized;
  const exact = EN_UI.get(normalized);
  if (exact) return exact;
  for (const [pattern, replace] of DYNAMIC_TRANSLATIONS) {
    if (pattern.test(normalized)) return normalized.replace(pattern, replace);
  }
  return normalized;
};

export const translateUiText = (value, language = "zh-CN") => {
  const source = String(value ?? "");
  if (language !== "en-US") return source;
  const trimmed = source.trim();
  const translated = translateTrimmed(trimmed);
  return translated === trimmed ? source : source.replace(trimmed, translated);
};

export const localizeDirectoryLabel = ({
  label = "",
  language = "zh-CN",
  moduleId = "",
  viewId = "default",
  folderId = "",
  custom = false,
  systemGenerated: _systemGenerated,
} = {}) => {
  const source = String(label);
  if (language !== "en-US") return source;
  const trimmed = source.trim();
  if (!custom && moduleId === "manuscript" && viewId === "novel" && String(folderId).startsWith("manuscript-volume:")) {
    const volume = trimmed.match(/^第\s*(\d+)\s*卷(?:[\s　:：·-]+(.*))?$/);
    if (volume) {
      const translated = `Volume ${volume[1]}${volume[2] ? ` ${volume[2].trim()}` : ""}`;
      return source.replace(trimmed, translated);
    }
  }
  if (custom) return source;
  return translateUiText(source, language);
};

const originalAttributes = new WeakMap();

const translateAttributeText = (element, value, language) => {
  if (language !== "en-US") return String(value ?? "");
  const source = String(value ?? "");
  if (element.matches?.("[data-skill-authored-attributes]")) {
    const skillDetail = source.trim().match(/^查看\s+(.+)\s+详情$/);
    if (skillDetail) return source.replace(source.trim(), `View ${skillDetail[1]} details`);
  }
  return translateUiText(source, language);
};

const excluded = (node) => node?.parentElement?.closest(UI_LOCALIZATION_EXCLUDE_SELECTOR);

const localizeTextNode = (node, language) => {
  if (excluded(node)) return;
  const previousSource = node.__shensiZhText;
  const current = node.nodeValue ?? "";
  const previousTranslation = previousSource == null ? "" : translateUiText(previousSource, "en-US");
  const source = previousSource == null || (/\p{Script=Han}/u.test(current) && current !== previousTranslation)
    ? current
    : previousSource;
  node.__shensiZhText = source;
  const next = language === "en-US" ? translateUiText(source, language) : source;
  if (current !== next) node.nodeValue = next;
};

const localizeAttributes = (element, language) => {
  if (element.matches?.(".project-row-main, .reference-tree-leaf, .document-row, .whiteboard-card")) return;
  const stored = originalAttributes.get(element) ?? {};
  for (const attribute of ["title", "aria-label", "placeholder"]) {
    if (!element.hasAttribute(attribute)) continue;
    const current = element.getAttribute(attribute) ?? "";
    const previousSource = stored[attribute];
    const previousTranslation = previousSource == null ? "" : translateAttributeText(element, previousSource, "en-US");
    const source = previousSource == null || (/\p{Script=Han}/u.test(current) && current !== previousTranslation)
      ? current
      : previousSource;
    stored[attribute] = source;
    const next = translateAttributeText(element, source, language);
    if (current !== next) element.setAttribute(attribute, next);
  }
  originalAttributes.set(element, stored);
};

export const localizeUi = (surface, language = "zh-CN") => {
  if (!surface) return;
  const localizationRoot = surface.matches?.("[data-ui-localization-root]")
    ? surface
    : surface.closest?.("[data-ui-localization-root]");
  const currentLanguage = localizationRoot?.dataset.uiLocalizationLanguage || "";
  // The shipped DOM and all normal render functions already author Chinese.
  // Walking the entire application (and every newly inserted whiteboard card)
  // only to write the same strings used to consume hundreds of milliseconds.
  // A real English -> Chinese switch still performs the full restoring pass.
  if (language !== "en-US" && currentLanguage !== "en-US") {
    document.documentElement.lang = "zh-CN";
    if (surface === localizationRoot) localizationRoot.dataset.uiLocalizationLanguage = "zh-CN";
    return;
  }
  document.documentElement.lang = language === "en-US" ? "en" : "zh-CN";
  if (surface.nodeType === Node.ELEMENT_NODE) localizeAttributes(surface, language);
  surface.querySelectorAll?.("[title],[aria-label],[placeholder]").forEach((element) => localizeAttributes(element, language));
  const walker = document.createTreeWalker(surface, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    localizeTextNode(node, language);
  }
  if (surface === localizationRoot) localizationRoot.dataset.uiLocalizationLanguage = language === "en-US" ? "en-US" : "zh-CN";
};

export const observeUiLocalization = (surface, languageProvider) => {
  if (surface?.dataset) surface.dataset.uiLocalizationRoot = "true";
  let scheduled = false;
  const pendingElements = new Set();
  const pendingTextNodes = new Set();
  const queueNode = (node) => {
    if (!node) return;
    if (node.nodeType === Node.TEXT_NODE) {
      pendingTextNodes.add(node);
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE) return;
    for (const parent of pendingElements) if (parent.contains(node)) return;
    for (const child of pendingElements) if (node.contains(child)) pendingElements.delete(child);
    pendingElements.add(node);
  };
  const localize = () => {
    scheduled = false;
    const language = languageProvider();
    const elements = [...pendingElements];
    const textNodes = [...pendingTextNodes];
    pendingElements.clear();
    pendingTextNodes.clear();
    for (const element of elements) {
      if (element !== surface && !surface.contains(element)) continue;
      localizeUi(element, language);
    }
    for (const node of textNodes) {
      if (!node.isConnected || !surface.contains(node)) continue;
      if (elements.some((element) => element.contains(node))) continue;
      localizeTextNode(node, language);
    }
  };
  const observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === "characterData" || record.type === "attributes") queueNode(record.target);
      else if (record.type === "childList") record.addedNodes.forEach(queueNode);
    }
    if (!pendingElements.size && !pendingTextNodes.size) return;
    if (scheduled) return;
    scheduled = true;
    queueMicrotask(localize);
  });
  observer.observe(surface, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ["title", "aria-label", "placeholder"],
  });
  localizeUi(surface, languageProvider());
  return observer;
};
